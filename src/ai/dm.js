/**
 * Компактный контекст текущего состояния для модели.
 * heroIdx — чей сейчас ход (в коопе героев несколько, и у каждого свой игрок).
 */
export function buildContext(state, playerInput, heroIdx = null) {
  const p = (heroIdx != null && state.heroes[heroIdx]) || state.player;
  const nearby = (state.monsters || [])
    .filter(m => m.hp > 0 && p.fov?.has(`${m.x},${m.y}`))
    .map(m => `${m.name} (HP ${m.hp}/${m.maxHp})`);
  const items = (state.floorItems || []).filter(it => p.fov?.has(`${it.x},${it.y}`)).map(i => i.name);
  const party = (state.heroes || [p]).map(h =>
    `${h.name} (${h.className}, HP ${h.hp}/${h.maxHp}${h.alive ? '' : ', МЁРТВ'}${h === p ? ' — ХОДИТ СЕЙЧАС' : ''})`
  ).join('; ');
  const others = (state.heroes || []).filter(h => h !== p).map(h => h.name);
  const abilityCdLeft = p.ability?.active ? Math.max(0, (p.abilityReady || 0) - state.turn) : 0;
  // проклятые вещи: ДМ должен обыгрывать симптом, но не выдумывать и не снимать проклятие
  const cursed = ['weapon', 'armor']
    .map(slot => p.equipment?.[slot])
    .filter(it => it && it.cursed);
  const curseLine = cursed.length
    ? `ПРОКЛЯТИЕ ${p.name}: ${cursed.map(it => `${it.name} («${it.curseName || '?'}»)${it.identified === false ? ' — пока не проявилось' : ''}`).join(', ')}. Обыгрывай симптом (шёпот, тяжесть, запах), но не снимай проклятие сам: это делает торговец за золото.`
    : '';
  const ability = p.ability
    ? `${p.ability.name} — актив: ${p.ability.active} (сила ${p.ability.power}, кулдаун ${p.ability.cd})` +
      (p.ability.passive ? `, пассив: ${p.ability.passive} (${p.ability.passivePower})` : '') +
      (abilityCdLeft > 0 ? `; сейчас восстанавливается ${abilityCdLeft} ход.` : '; готова к применению.')
    : 'нет';
  return [
    { role: 'system', content: SYSTEM_PROMPT },
    {
      role: 'user',
      content: [
        `МИР: ${state.worldDesc}. Режим: ${state.mode}. ${state.floorName}.`,
        state.worldBrief ? `КАНОН МИРА (правда, нельзя переписывать): ${state.worldBrief}` : '',
        (state.cast || []).length
          ? `ЗНАКОМЫЕ (уже встречались): ${state.cast.map(c => `${c.name}${c.role ? ` — ${c.role}` : ''}`).join('; ')}.`
          : '',
        state.backstory ? `ПРЕДЫСТОРИЯ (канон игрока, соблюдай и используй как зацепки): ${state.backstory}` : '',
        `ТЕКУЩИЙ ХОД: ${p.name} (${p.className}) — действие ниже принадлежит ЕМУ. Отвечай ему, обращайся по имени.`,
        `СПОСОБНОСТЬ ${p.name}: ${ability}.`,
        `СТАТЫ ${p.name}: ${Object.entries(p.stats).map(([k, v]) => `${k} ${v}`).join(', ')}, ур.${p.level}, HP ${p.hp}/${p.maxHp}, AC ${playerAc(p)}, золото ${p.gold}.`,
        `ИНВЕНТАРЬ ${p.name}: ${p.inventory.map(i => i.name).join(', ') || 'пуст'}; оружие: ${p.equipment.weapon?.name || 'кулаки'}; броня: ${p.equipment.armor?.name || 'нет'}.`,
        curseLine,
        `ПАРТИЯ: ${party}.`,
        others.length ? `ДРУГИЕ ГЕРОИ (за них играют другие люди, не действуй за них): ${others.join(', ')}.` : '',
        nearby.length ? `${p.name} ВИДИТ ВРАГОВ: ${nearby.join(', ')}.` : `${p.name} ВРАГОВ НЕ ВИДИТ.`,
        items.length ? `ВИДИТ ПРЕДМЕТЫ: ${items.join(', ')}.` : '',
        state.merchant
          ? `ТОРГОВЕЦ: ${state.merchant.name} — ${state.merchant.stock.map(i => `${i.name} (${i.price} зм)`).join(', ')}. Золото у ${p.name}: ${p.gold}.`
          : '',
        state.quests.length ? `КВЕСТЫ: ${state.quests.join('; ')}.` : '',
        (() => { const mem = memoryDigest(state, 12); return mem ? `НЕДАВНИЕ СОБЫТИЯ: ${mem}.` : ''; })(),
        (() => { const f = factsDigest(state); return f ? `ВАЖНОЕ (уже случилось, не забывать и не переигрывать): ${f}.` : ''; })(),
        (() => { const st = storyDigest(state); return st ? `СЮЖЕТ: ${st}` : ''; })(),
        state.story?.shape ? `ФОРМА ИСТОРИИ (веди её, не подменяй привычной): ${state.story.shape}.` : '',
        loadVillains().length ? `УЖЕ БЫЛИ ЗЛОДЕИ (не повторяй ни имя, ни мотив): ${loadVillains().join(', ')}.` : '',
        `ПРОВЕРКИ ДВИЖКА (последние): ${state.recentRolls?.join(', ') || 'нет'}.`,
        `ДЕЙСТВИЕ (${p.name}): "${playerInput}"`
      ].filter(Boolean).join('\n')
    }
  ];
}

/**
 * Стартовое вступление мира (учитывает всю партию, не только хоста).
 */
export function introMessages(state) {
  const heroes = state.heroes?.length ? state.heroes : [state.player];
  const partyLine = heroes.map(h => `${h.name} (${h.className}, ур.${h.level})`).join('; ');
  const coop = heroes.length > 1;
  const coopAsk = coop
    ? ` В партии ${heroes.length} героя, за каждого играет ОТДЕЛЬНЫЙ человек: ${partyLine}. Во вступлении представь КАЖДОГО героя ПО ИМЕНИ, опиши, где и рядом с кем он очнулся, и дай каждому личный интерес в истории (зацепку, страх, долг — своё для каждого). Дальнейшая история должна держать всех героев в сюжете, а не только первого.`
    : '';
  const storyAsk = state.mode === 'story'
    ? ` Это СЮЖЕТНЫЙ режим: придумай злодея (villain) и его страшную цель (villainGoal), намекни на него во вступлении.${loadVillains().length ? ` Злодеи прошлых забегов (не повторяй ни имя, ни мотив): ${loadVillains().join(', ')}.` : ''}` +
      (state.story?.shape ? ` ФОРМА ИСТОРИИ, которую нужно вести весь забег: ${state.story.shape}. Злодея и его мотив придумай под неё, а не «сбор монет/долгов».` : '')
    : '';
  const backAsk = state.backstory
    ? ` ПРЕДЫСТОРИЯ ОТ ИГРОКА (канон — соблюдай дословно, вплети в сцену и используй как зацепки, ничего не переписывай): ${state.backstory}`
    : '';
  const skillsLine = heroes
    .filter(h => h.ability?.name)
    .map(h => `${h.name} — «${h.ability.name}»`)
    .join('; ');
  return [
    { role: 'system', content: SYSTEM_PROMPT },
    {
      role: 'user',
      content: `Сгенерируй вступление новой игры. МИР: ${state.worldDesc}. Режим: ${state.mode}.${storyAsk} ГЕРОИ: ${partyLine}.${coopAsk}${backAsk}${skillsLine ? ` Способности героев: ${skillsLine}.` : ''} ${state.floorName}.

Вступление — единственная экспозиция, которую игрок получит до первых решений. Пиши её ПУНКТАМИ, без прозы и без воды:
1) worldBrief — КАНОН МИРА, 4 строки, каждая с новой строки и начинается с «— ». Строки по порядку: МЕСТО (где вообще происходит дело, эпоха, порядок вещей), ВЛАСТЬ (кто здесь правит или за что держатся люди), ЧТО СЛУЧИЛОСЬ (событие последних месяцев), СТРАХ (чего местные боятся). Конкретные названия, никаких «мрачный мир полон опасностей».
2) narrative — сцена старта, 3-4 КОРОТКИХ предложения: где очнулись, кто рядом, что прямо сейчас тянет вперёд. Каждому герою — своё место и своя зацепка (в коопе это обязательно, героев ${heroes.length}).
3) questAdd — 2-3 РАЗНЫЕ задачи, 3-8 слов каждая, с именами и местами: личная (про героя), местная (про людей вокруг), большая (про угрозу мира). Не дублируй их друг другом и больше задач в журнал не добавляй.
4) npcAdd — одно живое лицо в этой сцене: {"name","role"}.
5) И шутку в свой стиль — коротко, одной фразой.`
    }
  ];
}

/**
 * Предыстория героя/партии под сеттинг — то, что игрок потом правит руками.
 */
export function backstoryMessages(worldDesc, name, className, mode = 'story') {
  return [
    {
      role: 'system',
      content: `Ты пишешь предысторию героя для мира «${worldDesc}». Держись именно этого мира: его эпохи, технологий, слов и законов. Не сваливайся в тёмное фэнтези, если мир другой — никаких трактиров, эля и арбалетов в киберпанке. Отвечай ТОЛЬКО JSON без markdown. Тон — мрачный, но с чёрной иронией. Без воды и пафоса.`
    },
    {
      role: 'user',
      content: `МИР: ${worldDesc}. Герой: ${name}, класс ${className}. Режим: ${mode}.
Напиши предысторию на 90-140 слов, от третьего лица. Внутри должны быть: 1) откуда герой и чем жил до подземелья; 2) конкретная причина, по которой он здесь оказался (долг, вина, поиск, шантаж — выбери одно); 3) одна живая деталь-крючок (имя родственника/врага, вещь, шрам, обещание), за которую ДМ сможет тянуть сюжет. Без списков, без заголовков — связный текст.
JSON: {"backstory":"..."}`
    }
  ];
}

