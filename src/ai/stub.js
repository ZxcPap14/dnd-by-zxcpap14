// Один и тот же пул не должен выдать ту же строку два хода подряд.
const lastPick = new Map();

function pick(list, rng) {
  const last = lastPick.get(list);
  const opts = list.length > 1 ? list.filter(x => x !== last) : list;
  const v = opts[Math.floor(rng() * opts.length)];
  lastPick.set(list, v);
  return v;
}

export function resetStub() {
  lastPick.clear();
  snarkIdx = 0;
  questGiven = false;
  villainGiven = false;
}

/**
 * Ответ заглушки на свободное действие. Контракт тот же, что у ИИ:
 * возвращает эффекты для applyDmEffects.
 */
/** Как называть место в этом мире: «станция» вместо «подземелья». */
function placeWord(state) {
  const w = String(state?.worldDesc || '').toLowerCase();
  if (/косм|орбит|станц|звезд|экипаж/.test(w)) return 'станция';
  if (/пират|флот|остров|корабл/.test(w)) return 'корабль';
  if (/кибер|неон|корп|токио|город|улиц/.test(w)) return 'город';
  if (/школ|1999/.test(w)) return 'школа';
  if (/котельн|завод|смен|вахт/.test(w)) return 'завод';
  if (/пустош|постапок|радиац/.test(w)) return 'пустошь';
  return 'подземелье';
}

/** Одна и та же шутка, но про место игрока. */
function fitPlaces(effects, state) {
  const p = placeWord(state);
  const cap = p.charAt(0).toUpperCase() + p.slice(1);
  const fix = (t) => typeof t === 'string'
    ? t.replace(/Подземель/g, cap).replace(/подземель/g, p)
    : t;
  const walk = (value) => {
    if (typeof value === 'string') return fix(value);
    if (Array.isArray(value)) return value.map(walk);
    if (value && typeof value === 'object') {
      const out = {};
      for (const k of Object.keys(value)) out[k] = walk(value[k]);
      return out;
    }
    return value;
  };
  return walk(effects);
}

export function stubDmTurn(state, input) {
  return fitPlaces(stubTurn(state, input), state);
}

function stubTurn(state, input) {
  const rng = state.rng;
  const roll = rng();

  // сюжет: интро задаёт злодея (движок подставит офлайн-шаблон, если поле пустое)
  if (state.story && !villainGiven) {
    villainGiven = true;
    const heroes = state.heroes || [];
    const coop = heroes.length > 1;
    const names = heroes.map(h => h.name).join(' и ');
    const world = String(state.worldDesc || 'Классическое тёмное фэнтези').slice(0, 120);
    return {
      // Канон мира пунктами: заглушка берёт сеттинг игрока и достраивает его
      // до конкретики — место, власть, свежая беда, страх.
      worldBrief: [
        `— МЕСТО: ${world}.`,
        '— ВЛАСТЬ: дороги держат те, кто пережил прошлую зиму, и они не любят вопросов.',
        '— ЧТО СЛУЧИЛОСЬ: полгода назад с нижних уровней пошла молва — там кто-то поселился и требует дань.',
        '— СТРАХ: местные не спускаются ниже первого уровня и боятся, что однажды он поднимется сам.'
      ].join('\n'),
      narrative: coop
        ? `${names} очнулись в тёмном углу чужого мира. Где-то внизу что-то дышит и уже делит ваши жизни на планы. Постарайтесь не мешать друг другу. Сильно.`
        : 'Ты очнулся в тёмном углу чужого мира. Где-то внизу что-то дышит и уже загибает пальцы на твою жизнь.',
      questAdd: [
        coop ? 'Понять, что за долг висит на каждом' : 'Понять, что за долг висит на тебе',
        'Узнать, кто собирает дань с местных',
        'Дойти до самого дна'
      ],
      npcAdd: { name: 'Вельга', role: 'сборщица слухов у входа, знает всех' },
      suggestions: ['Осмотреться', 'Идти вглубь', 'Проверить инвентарь']
    };
  }
  // сюжет: в финальном акте нагнетаем
  if (state.story && state.story.act >= state.story.acts) {
    return {
      narrative: pick(ACT3_LINES, rng),
      suggestions: ['Идти навстречу судьбе', 'Потянуть время', 'Дрожать']
    };
  }

  // редкая встреча
  if (roll < 0.15 && !state.over) {
    return {
      narrative: pick(MEET_LINES, rng),
      enemySpawn: { name: 'неудобный знакомый', hp: 4 + state.depth, toHit: 2, dmg: 1, xp: 25 + state.depth * 5 },
      suggestions: ['Атаковать первым', 'Отступить в тень', 'Попробовать договориться']
    };
  }
  // редкий лут (описание предмета, а не готовый объект: id выдаст applyDmEffects)
  if (roll < 0.25 && !state.over) {
    return {
      narrative: pick(LOOT_LINES, rng),
      itemGain: { name: 'Зелье лечения', type: 'potion', heal: 8, qty: 1 },
      suggestions: ['Подобрать и выпить', 'Понюхать зелье', 'Идти дальше']
    };
  }
  // первый раз — даём квест
  if (!questGiven) {
    questGiven = true;
    const q = QUESTS[Math.floor(rng() * QUESTS.length)];
    return {
      narrative: `Твоя интуиция (а может, голод) подсказывает главное занятие: ${q}. Остальное — в твоих руках. Спойлер: руки у тебя кривые.`,
      questAdd: q,
      suggestions: ['Приступать немедля', 'Сначала осмотреться', 'Сделать вид, что не слышал']
    };
  }
  // проклятая вещь на теле — повод подколоть, а не менять правила
  const hero = state.heroes?.[state.activeIdx ?? 0];
  const cursedItem = ['weapon', 'armor'].map(s => hero?.equipment?.[s]).find(it => it && it.cursed);
  if (cursedItem && roll < 0.45) {
    return {
      narrative: pick(CURSE_TAUNTS, rng),
      suggestions: ['Потерпеть', 'Спросить торговца о проклятии', 'Делать вид, что так и надо']
    };
  }
  // ирония над сомнительной идеей
  if (/(украсть|обман|подкуп|взорвать|прыг|крич|сплюнуть|потрогать всё)/.test(input.toLowerCase())) {
    return { narrative: pick(BAD_IDEA, rng), suggestions: ['Осмотреться получше', 'Отступить в тень', 'Всё-таки сделать это'] };
  }
  return { narrative: SNARK[snarkIdx++ % SNARK.length], suggestions: ['Осмотреться', 'Идти дальше', 'Проверить инвентарь'] };
}
