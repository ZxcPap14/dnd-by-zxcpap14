// stub.js — офлайн-заглушка ДМа: играется без API-ключа.
// Тот же юмор и троллинг, но из заготовленного пула. Тот же JSON-контракт эффектов.

import { randomFloor } from '../engine/map.js';
import { makeItem } from '../engine/player.js';

const SNARK = [
  'Ты делаешь что-то настолько смелое, что даже тьма делает шаг назад. Из уважения. Или ужаса.',
  'Древние руны на стене складываются в слово «новичок». Совпадение? Не думаю.',
  'Где-то вдалеке кто-то смеётся. Возможно, это твоя судьба. Возможно, просто эхо.',
  'Ты чувствуешь, как приключение находит тебя. Оно шло за тобой с самого начала.',
  'Стены подземелья ведут себя подозрительно невинно. Слишком невинно.',
  'Мимокрокодил пробежал мимо и ничего не сказал. Странный день.',
  'Ты осматриваешься с таким лицом, будто знаешь, что делаешь. Подземелье решает подыграть.'
];

const BAD_IDEA = [
  'Идея так себе, но подземелье уважает смелость. Немного. Очень немного.',
  'Ты пробуешь. Подземелье пробует тебя. Угадай, у кого получилось лучше.',
  'Это сработает. Наверное. Где-нибудь. Но не сегодня и не здесь.'
];

const QUESTS = [
  'Найти выход из этого цирка',
  'Разобраться, кто здесь главный',
  'Пережить собственные решения',
  'Найти легендарный сэндвич 3-го этажа'
];

let snarkIdx = 0;
let questGiven = false;
let villainGiven = false;

export function resetStub() {
  snarkIdx = 0;
  questGiven = false;
  villainGiven = false;
}

/**
 * Ответ заглушки на свободное действие. Контракт тот же, что у ИИ:
 * возвращает эффекты для applyDmEffects.
 */
export function stubDmTurn(state, input) {
  const rng = state.rng;
  const roll = rng();

  // сюжет: интро задаёт злодея (движок подставит офлайн-шаблон, если поле пустое)
  if (state.story && !villainGiven) {
    villainGiven = true;
    const heroes = state.heroes || [];
    const coop = heroes.length > 1;
    const names = heroes.map(h => h.name).join(' и ');
    return {
      narrative: coop
        ? `${names} — вы очнулись в тёмном углу чужого мира, вокруг чужие планы и общая беда. Где-то глубоко внизу что-то дышит и загибает пальцы на ваши жизни. Спойлер: в конце коридора — оно. Постарайтесь не мешать друг другу. Сильно.`
        : 'Ты очнулся в тёмном углу чужого мира. Где-то глубоко внизу что-то дышит и загибает пальцы планы на твою жизнь. Спойлер: в конце коридора — оно.',
      questAdd: 'Дойти до дна подземелья',
      suggestions: ['Осмотреться', 'Идти вглубь', 'Проверить инвентарь']
    };
  }
  // сюжет: в финальном акте нагнетаем
  if (state.story && state.story.act >= state.story.acts) {
    return {
      narrative: 'Стены дрожат от чужой воли. Дно уже близко, и оно знает, что ты идёшь. Оно радуется. Плохой знак.',
      suggestions: ['Идти навстречу судьбе', 'Потянуть время', 'Дрожать']
    };
  }

  // редкая встреча
  if (roll < 0.15 && !state.over) {
    const pos = randomFloor(rng, state.dungeon);
    return {
      narrative: `От тьмы отделяется ${'нечто недоброе'}. Похоже, тишина тебе не понравилась.`,
      enemySpawn: { name: 'неудобный знакомый', hp: 4 + state.depth, toHit: 2, dmg: 1, xp: 25 + state.depth * 5 },
      suggestions: ['Атаковать первым', 'Отступить в тень', 'Попробовать договориться']
    };
  }
  // редкий лут
  if (roll < 0.25 && !state.over) {
    return {
      narrative: 'Ты нащупываешь в темноте что-то полезное. Подземелье сегодня щедрое. Подозрительно.',
      itemGain: makeItem({ name: 'Зелье лечения', type: 'potion', heal: 8 }),
      suggestions: ['Подобрать и выпить', 'Понюхать зелье', 'Идти дальше']
    };
  }
  // первый раз — даём квест
  if (!questGiven) {
    questGiven = true;
    const q = QUESTS[Math.floor(rng() * QUESTS.length)];
    return {
      narrative: `Твоя интуиция (а может, голод) подсказывает главное занятие: ${q}. Остальное — в твоих руках. Спойлер: руки у тебя кривые.`,
      questAdd: q,
      suggestions: ['Приступать немедля', 'Сначала осмотреться', 'Сделать вид, что не слышал']
    };
  }
  // ирония над сомнительной идеей
  if (/(украсть|обман|подкуп|взорвать|прыг|крич|сплюнуть|потрогать всё)/.test(input.toLowerCase())) {
    return { narrative: BAD_IDEA[Math.floor(rng() * BAD_IDEA.length)], suggestions: ['Осмотреться получше', 'Отступить в тень', 'Всё-таки сделать это'] };
  }
  return { narrative: SNARK[snarkIdx++ % SNARK.length], suggestions: ['Осмотреться', 'Идти дальше', 'Проверить инвентарь'] };
}
